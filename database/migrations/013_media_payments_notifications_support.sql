-- Cloudinary remains the binary store. This table owns lifecycle and purpose;
-- KYC assets have no automatic deletion date, while other media expires after
-- 30 days. Public IDs are generated by the API and never accepted from users.
CREATE TABLE IF NOT EXISTS media_assets (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 public_id text NOT NULL UNIQUE,
 asset_category text NOT NULL CHECK(asset_category IN ('PROFILE_PHOTO','KYC_DOCUMENT','VEHICLE_PHOTO','CHAT_ATTACHMENT','SUPPORT_ATTACHMENT')),
 resource_type text NOT NULL CHECK(resource_type IN ('image','raw','video')),
 format text NOT NULL,
 bytes bigint NOT NULL CHECK(bytes>=0),
 secure_url text NOT NULL,
 source_public_id text,
 is_kyc boolean NOT NULL DEFAULT false,
 uploaded_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz,
 deletion_status text NOT NULL DEFAULT 'ACTIVE' CHECK(deletion_status IN ('ACTIVE','DELETE_PENDING','DELETED','DELETE_FAILED')),
 deleted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((is_kyc AND expires_at IS NULL) OR (NOT is_kyc AND expires_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS media_assets_expiry_idx ON media_assets(expires_at) WHERE deletion_status IN ('ACTIVE','DELETE_FAILED') AND NOT is_kyc;
CREATE INDEX IF NOT EXISTS media_assets_owner_idx ON media_assets(user_id,asset_category,created_at DESC);
ALTER TABLE media_assets ALTER COLUMN secure_url DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_photo_media_id uuid REFERENCES media_assets(id);
ALTER TABLE media_assets ADD COLUMN IF NOT EXISTS upload_status text NOT NULL DEFAULT 'UPLOADED' CHECK(upload_status IN ('PENDING','UPLOADED','REJECTED'));
ALTER TABLE media_assets ADD COLUMN IF NOT EXISTS delivery_type text NOT NULL DEFAULT 'authenticated' CHECK(delivery_type IN ('upload','private','authenticated'));

-- Submitted vehicle and bike registrations refer to uploaded media records,
-- allowing KYC review without copying or duplicating the Cloudinary files.
CREATE TABLE IF NOT EXISTS vehicle_registrations (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 owner_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 vehicle_type text NOT NULL CHECK(vehicle_type IN ('BUS_14_SEATER','BUS_18_SEATER','COASTER','SIENNA','BIKE','DISPATCH_BIKE')),
 plate_number text NOT NULL UNIQUE,
 seat_capacity integer NOT NULL CHECK(seat_capacity BETWEEN 1 AND 100),
 make text NOT NULL,
 model text NOT NULL,
 model_year integer NOT NULL CHECK(model_year BETWEEN 1970 AND 2100),
 drivers_license_media_id uuid REFERENCES media_assets(id),
 vehicle_license_media_id uuid REFERENCES media_assets(id),
 road_worthiness_media_id uuid REFERENCES media_assets(id),
 profile_photo_media_id uuid REFERENCES media_assets(id),
 dispatch_box_media_id uuid REFERENCES media_assets(id),
 dispatch_permit_media_id uuid REFERENCES media_assets(id),
 hardware_gps_imei text UNIQUE,
 verification_status text NOT NULL DEFAULT 'PENDING' CHECK(verification_status IN ('PENDING','APPROVED','REJECTED')),
 rejection_reason text,
 reviewed_by uuid REFERENCES users(id),
 reviewed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS vehicle_registrations_owner_idx ON vehicle_registrations(owner_id,created_at DESC);
CREATE INDEX IF NOT EXISTS vehicle_registrations_review_idx ON vehicle_registrations(verification_status,created_at) WHERE verification_status='PENDING';

CREATE TABLE IF NOT EXISTS kyc_reviews (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 vehicle_registration_id uuid REFERENCES vehicle_registrations(id) ON DELETE CASCADE,
 reviewer_id uuid REFERENCES users(id),
 status text NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 notes text,
 submitted_at timestamptz NOT NULL DEFAULT now(),
 reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS kyc_reviews_pending_idx ON kyc_reviews(submitted_at) WHERE status='PENDING';

-- Payment intents are durable idempotency anchors. Amounts are stored in kobo
-- for Paystack and the resulting ledger records are written only after verified
-- provider settlement.
CREATE TABLE IF NOT EXISTS payment_intents (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id uuid NOT NULL REFERENCES users(id),
 intent_type text NOT NULL CHECK(intent_type IN ('WALLET_FUNDING','TICKET_CHECKOUT','SUBSCRIPTION','VTU_DATA','AMEBO_TOKENS','RIDER_ORDER')),
 payment_method text NOT NULL CHECK(payment_method IN ('PAYSTACK','WALLET')),
 idempotency_key text NOT NULL,
 provider_reference text UNIQUE,
 amount_kobo bigint NOT NULL CHECK(amount_kobo>0),
 currency char(3) NOT NULL DEFAULT 'NGN' CHECK(currency='NGN'),
 status text NOT NULL DEFAULT 'CREATED' CHECK(status IN ('CREATED','PENDING','SUCCEEDED','FAILED','CANCELLED','REFUNDED')),
 purpose_id uuid,
 metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
 authorization_url text,
 access_code text,
 expires_at timestamptz,
 settled_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,idempotency_key)
);
CREATE INDEX IF NOT EXISTS payment_intents_user_idx ON payment_intents(user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS payment_intents_pending_idx ON payment_intents(created_at) WHERE status IN ('CREATED','PENDING');

