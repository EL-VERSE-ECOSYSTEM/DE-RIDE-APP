CREATE TABLE IF NOT EXISTS support_cases (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 requester_id uuid NOT NULL REFERENCES users(id),
 assigned_admin_id uuid REFERENCES users(id),
 trip_id uuid REFERENCES trips(id),
 ride_order_id uuid REFERENCES ride_orders(id),
 subject text NOT NULL,
 category text NOT NULL CHECK(category IN ('ACCOUNT','PAYMENT','TRIP','KYC','SAFETY','OTHER')),
 status text NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','IN_PROGRESS','WAITING_FOR_USER','RESOLVED','CLOSED')),
 priority text NOT NULL DEFAULT 'NORMAL' CHECK(priority IN ('LOW','NORMAL','HIGH','URGENT')),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 resolved_at timestamptz
);
CREATE INDEX IF NOT EXISTS support_cases_user_idx ON support_cases(requester_id,created_at DESC);
CREATE INDEX IF NOT EXISTS support_cases_queue_idx ON support_cases(priority,created_at) WHERE status IN ('OPEN','IN_PROGRESS','WAITING_FOR_USER');

CREATE TABLE IF NOT EXISTS support_messages (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 case_id uuid NOT NULL REFERENCES support_cases(id) ON DELETE CASCADE,
 sender_id uuid NOT NULL REFERENCES users(id),
 body text NOT NULL CHECK(length(body) BETWEEN 1 AND 5000),
 attachment_media_id uuid REFERENCES media_assets(id),
 internal_note boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_messages_case_idx ON support_messages(case_id,created_at);

CREATE TABLE IF NOT EXISTS disputes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 escalation_id uuid REFERENCES escalations(id),
 payment_intent_id uuid REFERENCES payment_intents(id),
 opened_by uuid NOT NULL REFERENCES users(id),
